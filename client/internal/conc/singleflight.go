package conc

import (
	"fmt"
	"runtime/debug"
	"sync"

	"github.com/cockroachdb/errors"
)

// panicError is an error generated by a panicking caller, wrapped so waiting
// callers re-panic instead of receiving a nil value.
type panicError struct {
	message any
	stack   []byte
}

func (p *panicError) Error() string {
	return fmt.Sprintf("panic: %v", p.message)
}

var errPanic = errors.New("panic: singleflight called fn which panicked")

type call[T any] struct {
	wg   sync.WaitGroup
	val  T
	err  error
	dups int
}

// Singleflight coalesces concurrent calls with the same key into a single
// execution of fn. Unlike the standard library's string-keyed singleflight,
// the key is a comparable type, so callers are not forced to flatten a
// structured key into a delimiter-joined string (which can collide).
type Singleflight[T any, K comparable] struct {
	mu    sync.Mutex
	calls map[K]*call[T]
}

// Do runs fn for key and returns the value and error, deduplicating concurrent
// calls with the same key. The bool reports whether the result was shared with
// another concurrent caller.
func (sf *Singleflight[T, K]) Do(key K, fn func() (T, error)) (T, error, bool) {
	sf.mu.Lock()
	if sf.calls == nil {
		sf.calls = make(map[K]*call[T])
	}
	if c, ok := sf.calls[key]; ok {
		c.dups++
		sf.mu.Unlock()
		c.wg.Wait()
		if e, ok := c.err.(*panicError); ok {
			panic(e)
		}
		return c.val, c.err, true
	}
	c := new(call[T])
	c.wg.Add(1)
	sf.calls[key] = c
	sf.mu.Unlock()

	sf.doCall(c, key, fn)
	return c.val, c.err, c.dups > 0
}

func (sf *Singleflight[T, K]) doCall(c *call[T], key K, fn func() (T, error)) {
	normalReturn := false
	recoveredPanic := false
	defer func() {
		if !normalReturn && !recoveredPanic {
			c.err = errPanic
		}
		sf.mu.Lock()
		delete(sf.calls, key)
		sf.mu.Unlock()
		c.wg.Done()
	}()
	func() {
		defer func() {
			if !normalReturn {
				// recover unconditionally: on Go >= 1.21 a panic(nil) is
				// surfaced as a non-nil runtime.PanicNilError, and a plain
				// panic(V) yields V. Either way it must be wrapped so waiting
				// callers re-panic instead of observing a nil value.
				r := recover()
				c.err = newPanicError(r)
				recoveredPanic = true
			}
		}()
		c.val, c.err = fn()
		normalReturn = true
	}()
	if recoveredPanic {
		panic(c.err)
	}
}

func newPanicError(message any) *panicError {
	panicErr := &panicError{message: message}
	panicErr.stack = debug.Stack()
	return panicErr
}
