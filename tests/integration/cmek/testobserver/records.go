// Package testobserver carries read-only CMEK flush evidence between the
// MiniCluster server processes and the integration test runner. Production
// builds do not install its recorder.
package testobserver

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"sync"

	"github.com/cockroachdb/errors"
)

const (
	DirectoryEnv = "MILVUS_CMEK_OBSERVER_DIR"
	TokenEnv     = "MILVUS_CMEK_OBSERVER_TOKEN" //nolint:gosec // Environment variable name; the run token is generated by the test runner.
)

type Record struct {
	Token          string          `json:"token"`
	NodeID         int64           `json:"node_id"`
	PID            int             `json:"pid"`
	Sequence       uint64          `json:"sequence"`
	Event          string          `json:"event"`
	TaskID         uint64          `json:"task_id,omitempty"`
	TaskType       string          `json:"task_type,omitempty"`
	CollectionID   int64           `json:"collection_id"`
	PartitionID    int64           `json:"partition_id,omitempty"`
	SegmentID      int64           `json:"segment_id,omitempty"`
	Channel        string          `json:"channel"`
	StorageVersion int64           `json:"storage_version,omitempty"`
	Rows           int64           `json:"rows,omitempty"`
	FieldRows      map[int64]int64 `json:"field_rows,omitempty"`
	Manifest       string          `json:"manifest,omitempty"`
	Success        bool            `json:"success"`
}

type Recorder struct {
	mu        sync.Mutex
	directory string
	token     string
	nodeID    int64
	pid       int
	sequence  uint64
	contents  []byte
}

func NewRecorder(directory, token string, nodeID int64, pid int) (*Recorder, error) {
	if !filepath.IsAbs(directory) || token == "" || nodeID <= 0 || pid <= 0 {
		return nil, errors.New("invalid observer directory, token or process identity")
	}
	info, err := os.Stat(directory)
	if err != nil {
		return nil, err
	}
	if !info.IsDir() {
		return nil, errors.New("observer directory is not a directory")
	}
	r := &Recorder{directory: directory, token: token, nodeID: nodeID, pid: pid}
	if _, err := os.Stat(r.path()); !os.IsNotExist(err) {
		return nil, errors.New("observer file already exists or cannot be checked")
	}
	return r, nil
}

func (r *Recorder) path() string {
	return filepath.Join(r.directory, fmt.Sprintf("%d-%d.jsonl", r.nodeID, r.pid))
}

// Each replacement is a complete JSONL snapshot. Readers cannot mistake a
// concurrent append's partial line for a corrupt record; sequence validation
// still detects lost records in the snapshot.
func (r *Recorder) Append(record Record) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	record.Token, record.NodeID, record.PID = r.token, r.nodeID, r.pid
	record.Sequence = r.sequence + 1
	encoded, err := json.Marshal(record)
	if err != nil {
		return err
	}
	next := append(append([]byte(nil), r.contents...), append(encoded, '\n')...)
	file, err := os.CreateTemp(r.directory, ".observer-")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(next); err != nil {
		_ = file.Close()
		return err
	}
	if err := file.Sync(); err != nil {
		_ = file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	if err := os.Rename(file.Name(), r.path()); err != nil {
		return err
	}
	r.contents, r.sequence = next, record.Sequence
	return nil
}

// ReadRecords validates every record before the caller filters collections.
// owners maps actual MiniCluster node IDs to their child process IDs.
func ReadRecords(directory, token string, owners map[int64]int) ([]Record, error) {
	files, err := filepath.Glob(filepath.Join(directory, "*.jsonl"))
	if err != nil {
		return nil, err
	}
	var records []Record
	for _, name := range files {
		raw, err := os.ReadFile(name)
		if err != nil {
			return nil, err
		}
		if len(raw) == 0 || raw[len(raw)-1] != '\n' {
			return nil, errors.New("truncated observer record")
		}
		decoder := json.NewDecoder(bytes.NewReader(raw))
		decoder.DisallowUnknownFields()
		for sequence := uint64(1); ; sequence++ {
			var record Record
			if err := decoder.Decode(&record); err == io.EOF {
				break
			} else if err != nil {
				return nil, errors.Wrap(err, "invalid observer record")
			}
			if record.Token != token {
				return nil, errors.New("observer token mismatch")
			}
			if owners[record.NodeID] != record.PID || record.PID <= 0 || record.NodeID <= 0 {
				return nil, errors.New("observer owner mismatch")
			}
			if filepath.Base(name) != fmt.Sprintf("%d-%d.jsonl", record.NodeID, record.PID) {
				return nil, errors.New("observer filename owner mismatch")
			}
			if record.Sequence != sequence {
				return nil, errors.New("observer sequence gap or duplicate")
			}
			switch record.Event {
			case "registered", "commit", "task":
			default:
				return nil, errors.New("unknown observer event")
			}
			records = append(records, record)
		}
	}
	return records, nil
}

// CanonicalFlushes accepts only a positive-row SyncTask whose actual
// SaveBinlogPaths RPC was acknowledged and whose completion callback succeeded.
// An UpdateSync nil return alone is insufficient: it also suppresses some
// stale-segment and channel errors in production.
func CanonicalFlushes(records []Record, collectionID int64, channels map[string]bool, rows int64) ([]Record, bool, error) {
	type taskKey struct {
		node int64
		pid  int
		task uint64
	}
	type ownerKey struct {
		node    int64
		pid     int
		channel string
	}
	registered := make(map[ownerKey]bool)
	commits := make(map[taskKey]Record)
	var completed []Record
	for _, record := range records {
		if record.CollectionID != collectionID {
			continue
		}
		if !channels[record.Channel] {
			return nil, false, errors.New("unexpected flush channel")
		}
		owner := ownerKey{record.NodeID, record.PID, record.Channel}
		if record.Event == "registered" {
			registered[owner] = true
			continue
		}
		if !registered[owner] {
			return nil, false, errors.New("flush task has no registered owner")
		}
		if record.TaskType != "SyncTask" {
			return nil, false, errors.New("flush did not use canonical SyncTask")
		}
		key := taskKey{record.NodeID, record.PID, record.TaskID}
		if key.task == 0 {
			return nil, false, errors.New("flush task has no identity")
		}
		if record.Event == "commit" {
			if record.Success {
				commits[key] = record
			}
			continue
		}
		if !record.Success {
			return nil, false, errors.New("flush task failed")
		}
		if record.Rows == 0 {
			continue
		}
		commit, ok := commits[key]
		if !ok {
			return nil, false, errors.New("task succeeded without an acknowledged DataCoord commit")
		}
		if record.StorageVersion != 3 || record.Rows <= 0 || record.Manifest == "" || len(record.FieldRows) == 0 {
			return nil, false, errors.New("task has no nonempty storage v3 writer output")
		}
		if commit.Manifest != record.Manifest || commit.Rows != record.Rows || commit.Channel != record.Channel || commit.PartitionID != record.PartitionID ||
			commit.SegmentID != record.SegmentID || commit.StorageVersion != record.StorageVersion || !reflect.DeepEqual(commit.FieldRows, record.FieldRows) {
			return nil, false, errors.New("writer output differs from acknowledged commit")
		}
		for _, count := range record.FieldRows {
			if count != record.Rows {
				return nil, false, errors.New("insert binlog row count does not match writer output")
			}
		}
		delete(commits, key)
		completed = append(completed, record)
	}
	var total int64
	seen := make(map[string]bool)
	for _, record := range completed {
		identity := fmt.Sprintf("%d/%s", record.SegmentID, record.Manifest)
		if seen[identity] {
			return nil, false, errors.New("writer output counted more than once")
		}
		seen[identity] = true
		total += record.Rows
	}
	if total > rows {
		return nil, false, errors.New("writer output exceeds inserted row count")
	}
	sort.Slice(completed, func(i, j int) bool { return completed[i].SegmentID < completed[j].SegmentID })
	return completed, total == rows && len(completed) > 0, nil
}
