// nonSourceFieldIDs returns field IDs absent from import source files: the
// autoID primary key (generated by Milvus) and all function-output fields
// (generated during import, e.g. a BM25 sparse vector).
func nonSourceFieldIDs(schema *schemapb.CollectionSchema) typeutil.Set[int64] {
	ids := typeutil.NewSet[int64]()
	for _, f := range schema.GetFields() {
		if f.GetIsPrimaryKey() && f.GetAutoID() {
			ids.Insert(f.GetFieldID())
		}
		// The dynamic field is never required from the source file: the JSON row
		// parser leaves it out of name2FieldID (json/row_parser.go:80-83), so the
		// completeness check never asks for it and combineDynamicRow synthesizes
		// it from the row's spare keys. The nullable/default skip below covers it
		// only for collections created after $meta gained those attributes; a
		// schema persisted before that is neither, and nothing migrated it.
		if f.GetIsDynamic() {
			ids.Insert(f.GetFieldID())
		}
	}
	for _, fn := range schema.GetFunctions() {
		ids.Insert(fn.GetOutputFieldIds()...)
	}
	return ids
}

// minRowTextBytes returns a provable lower bound on the number of bytes one row
// occupies in a text import file of type ft, EXCLUDING fields not present in the
// source files (autoID primary key and function-output fields).
//
// Two parts contribute. The per-field value floor is format-independent: a known
// dense vector needs at least one character per element (dim, or dim/8 for binary
// vectors); every other known fixed scalar needs at least 1; VarChar/JSON may be
// empty and unknown/sparse source fields need none.
//
// The structural floor is NOT format-independent, and it is what keeps a large
// all-VarChar file from being estimated at one row per byte: a JSON row spells out
// every field name it carries, paying {"name": per field, whereas a CSV row carries
// only separators because its names live in the header.
//
// Row separators are NOT part of this floor. A single-row file has none, so
// charging one here would let the floor exceed a real row and under-count the
// file -- the one direction this bound may never take. Rows do still cost a
// separator between them, but that is n-1 for n rows, an off-by-one the caller
// applies to the whole file rather than to each row; see RowCountUpperBound.
//
// The second return value reports whether the floor was clamped, i.e. whether
// nothing about this schema was actually provable and the 1 below is a
// placeholder to avoid divide-by-zero rather than a real byte cost. The caller
// needs the distinction: a clamped floor cannot carry the per-file separator
// correction, because rows really can occupy fewer bytes than the floor claims.
func minRowTextBytes(schema *schemapb.CollectionSchema, ft FileType) (int64, bool) {
	// A JSON row is an object: braces around it, and "name": before each value.
	jsonShaped := ft == JSON || ft == JSONLines
	skip := nonSourceFieldIDs(schema)
	var total, present int64
	for _, field := range schema.GetFields() {
		if skip.Contain(field.GetFieldID()) {
			continue
		}
		// A nullable or defaulted field may be omitted entirely from a JSON row
		// (the reader fills it), contributing 0 bytes. Counting it would overstate
		// the per-row floor and understate the row count, so skip it to keep this a
		// true lower bound.
		if field.GetNullable() || field.GetDefaultValue() != nil {
			continue
		}
		present++
		if jsonShaped {
			// Two quotes and a colon around the field name.
			total += int64(len(field.GetName())) + 3
		}
		switch field.GetDataType() {
		case schemapb.DataType_Bool, schemapb.DataType_Int8, schemapb.DataType_Int16,
			schemapb.DataType_Int32, schemapb.DataType_Int64,
			schemapb.DataType_Float, schemapb.DataType_Double:
			// Known fixed scalar: at least 1 character.
			total++
		case schemapb.DataType_FloatVector, schemapb.DataType_Float16Vector,
			schemapb.DataType_BFloat16Vector, schemapb.DataType_Int8Vector:
			dim, err := typeutil.GetDim(field)
			if err != nil {
				// Unknown dimension: cannot prove a floor, contributes 0.
				continue
			}
			total += dim
		case schemapb.DataType_BinaryVector:
			dim, err := typeutil.GetDim(field)
			if err != nil {
				continue
			}
			total += dim / 8
		default:
			// VarChar/JSON may be empty; unknown/sparse source fields contribute 0.
		}
	}
	if present > 1 {
		// One separator between adjacent fields: ',' in both formats.
		total += present - 1
	}
	if jsonShaped {
		total += 2 // the row object's braces
	}
	if total < 1 {
		return 1, true
	}
	return total, false
}

// RowCountUpperBound returns an upper bound on the row count of one
// ImportFile, and whether that bound is exact. Parquet and numpy record their row
// count in the file itself (footer num_rows / header shape), so both are exact.
// JSON/CSV record nothing, so their bound divides Σ file size by a provable
// per-row byte floor -- a heavy over-estimate that is still guaranteed not to
// under-count. The exactness decides how the caller sizes the reservation and,
// under ID pressure, which reservations it may shrink.
//
// The per-format dispatch mirrors NewReader's: whatever knowledge of a format's
// layout this needs belongs in that format's package, next to the reader whose
// rules it must agree with.
func RowCountUpperBound(ctx context.Context, cm storage.ChunkManager,
	schema *schemapb.CollectionSchema, file *internalpb.ImportFile,
) (int64, bool, error) {
	ft, err := GetFileType(file)
	if err != nil {
		return 0, false, err
	}

	sumSize := func() (int64, error) {
		var total int64
		for _, path := range file.GetPaths() {
			size, err := cm.Size(ctx, path)
			if err != nil {
				return 0, err
			}
			total += size
		}
		return total, nil
	}

	var bound int64
	var exact bool
	switch ft {
	case Parquet:
		bound, err = parquet.NumRows(ctx, cm, file.GetPaths()[0])
		if err != nil {
			return 0, false, err
		}
		exact = true
	case Numpy:
		bound, err = numpy.NumRows(ctx, cm, schema, file.GetPaths())
		if err != nil {
			return 0, false, err
		}
		exact = true
	case JSON, CSV, JSONLines:
		// No row count is recorded in the file, so divide the byte size by a
		// provable per-row floor. This over-estimates heavily (the floor is 1 byte
		// for an all-VarChar schema) and must stay an upper bound: under-estimating
		// would exhaust the range and fail the import at the datanode guard.
		minRow, clamped := minRowTextBytes(schema, ft)
		total, err := sumSize()
		if err != nil {
			return 0, false, err
		}
		if clamped {
			// Nothing about the schema was provable, so the floor is a placeholder
			// and rows may genuinely be smaller than it: a single-column CSV of
			// empty values is one newline per row, n rows in n bytes. Only the
			// loose form holds.
			bound = total/minRow + 1
		} else {
			// The floor is real, so n rows also pay n-1 row separators:
			// n*minRow + (n-1) <= total, i.e. n <= (total+1)/(minRow+1). Charging
			// the separator per row instead would over-count a single-row file,
			// which is why it is corrected here and not inside minRowTextBytes.
			bound = (total+1)/(minRow+1) + 1
		}
	default:
		return 0, false, merr.WrapErrImportFailed("unknown import file type for PK range sizing")
	}

	if bound < 0 {
		bound = 0
	}
	return bound, exact, nil
}
