inline bool
StrictGroupWorkExceedsLimit(double estimated_candidates) {
    return estimated_candidates > kStrictGroupRemainingCandidateLimit;
}

// Equal-frequency, stationary groups; arrivals to each group are approximated
// by a Poisson process of rate 1 / estimated_groups. A quota r has a Gamma(r,1)
// waiting time in normalized units. Integrate the survival function of the
// maximum waiting time, then scale back to consumer candidates.
inline double
EstimateStrictGroupRemainingCandidates(
    double estimated_groups, const std::vector<size_t>& remaining_quotas) {
    std::map<size_t, size_t> quota_counts;
    size_t groups = 0;
    size_t max_quota = 0;
    for (auto quota : remaining_quotas) {
        if (quota > 0) {
            ++quota_counts[quota];
            ++groups;
            max_quota = std::max(max_quota, quota);
        }
    }
    if (groups == 0) {
        return 0;
    }
    if (groups == 1) {
        return estimated_groups * max_quota;
    }
    if (max_quota == 1) {
        double harmonic = 0;
        for (size_t i = 1; i <= groups; ++i) {
            harmonic += 1.0 / i;
        }
        return estimated_groups * harmonic;
    }
    auto survival = [&](double x) {
        double log_cdf = 0;
        for (const auto& [quota, count] : quota_counts) {
            const auto cdf =
                boost::math::gamma_p(static_cast<double>(quota), x);
            if (cdf <= 0) {
                return 1.0;
            }
            log_cdf += count * std::log(cdf);
        }
        return -std::expm1(log_cdf);
    };
    // Gamma concentration + union bound: truncate far beyond the last group's
    // typical completion time. Work depends on quotas, never on segment rows.
    const double tail = std::log(static_cast<double>(groups)) + 40;
    const double upper =
        max_quota + std::sqrt(2.0 * max_quota * tail) + 2 * tail;
    return estimated_groups *
           boost::math::quadrature::gauss_kronrod<double, 15>::integrate(
               survival, 0.0, upper, 8, 1e-7);
}

