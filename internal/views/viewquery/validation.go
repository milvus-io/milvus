package viewquery

import (
	"github.com/milvus-io/milvus/internal/views/viewerror"
	"github.com/milvus-io/milvus/pkg/v3/proto/viewpb"
)

func validateSearchRequest(req *viewpb.SearchOnViewRequest) error {
	if req.GetLegacyReq() == nil {
		return invalidRequest("missing legacy search request")
	}
	return validateCommonRequestShape(req.GetShardId(), req.GetVersion(), req.GetMvcc())
}

func validateQueryRequest(req *viewpb.QueryOnViewRequest) error {
	if req.GetLegacyReq() == nil {
		return invalidRequest("missing legacy query request")
	}
	return validateCommonRequestShape(req.GetShardId(), req.GetVersion(), req.GetMvcc())
}

func validateCommonRequestShape(shardID *viewpb.ShardID, version *viewpb.QueryViewVersion, mvcc *viewpb.QueryPlanMVCC) error {
	if shardID == nil {
		return invalidRequest("missing shard id")
	}
	if shardID.GetVchannel() == "" {
		return invalidRequest("empty vchannel")
	}
	if version == nil || version.GetDataVersion() == nil {
		return invalidRequest("missing query view version")
	}
	if mvcc == nil {
		return invalidRequest("missing query plan mvcc")
	}
	return nil
}

func invalidRequest(reason string) error {
	// These requests are generated by internal query clients, not SDK users.
	return viewerror.NewUnknownError(reason)
}
