var updateSurface = flag.Bool("update-surface", false, "rewrite testdata/report_surface.golden from the current code")

const surfaceFile = "testdata/report_surface.golden"

// The report is read by a system outside this repository. Renaming a group,
// renaming a counter or dropping one is a breaking change for that consumer
// even though nothing in Milvus fails to compile. This test pins the whole
// emitted surface to a checked-in file, so any such change has to be made
// deliberately, in a diff a reviewer can see.
//
// Adding a counter is expected and cheap: run
//
//	go test ./internal/featureusage/ -run TestReportSurfaceIsStable -update-surface
//
// and commit the updated file together with the change.
func TestReportSurfaceIsStable(t *testing.T) {
	got := renderSurface()

	if *updateSurface {
		require.NoError(t, os.MkdirAll(filepath.Dir(surfaceFile), 0o755))
		require.NoError(t, os.WriteFile(surfaceFile, []byte(got), 0o600))
		t.Log("surface file rewritten")
		return
	}

	wantBytes, err := os.ReadFile(surfaceFile)
	require.NoError(t, err, "golden surface file missing; regenerate with -update-surface")

	removed, added := diffLines(string(wantBytes), got)
	if len(removed) == 0 && len(added) == 0 {
		return
	}
	t.Errorf("the reported groups or counters changed.\n"+
		"gone (breaking for the report consumer):\n  %s\n"+
		"new:\n  %s\n"+
		"If the change is intended, rerun with -update-surface and commit %s.",
		strings.Join(removed, "\n  "), strings.Join(added, "\n  "), surfaceFile)
}

// diffLines reports the lines only in want and the lines only in got. Order
// changes are not reported: the consumer keys on the names, not their order.
func diffLines(want, got string) (removed, added []string) {
	set := func(s string) map[string]bool {
		out := map[string]bool{}
		for _, line := range strings.Split(s, "\n") {
			if line != "" && !strings.HasPrefix(line, "#") {
				out[line] = true
			}
		}
		return out
	}
	w, g := set(want), set(got)
	for line := range w {
		if !g[line] {
			removed = append(removed, line)
		}
	}
	for line := range g {
		if !w[line] {
			added = append(added, line)
		}
	}
	sort.Strings(removed)
	sort.Strings(added)
	return removed, added
}

// renderSurface lists every group and every counter, one per line, sorted by
// nothing: the order is the code's own, so a reordering also shows up.
func renderSurface() string {
	var b strings.Builder
	b.WriteString("# Every group and counter the feature usage report can emit.\n")
	b.WriteString("# Generated by TestReportSurfaceIsStable -update-surface. Do not edit by hand.\n")
	for _, g := range AllGroups() {
		fmt.Fprintf(&b, "group\t%s\n", g)
	}
	for f := Feature(0); f < numFeatures; f++ {
		fmt.Fprintf(&b, "counter\t%s\t%s\n", f.Role(), f.Name())
	}
	return b.String()
}

// Every group named in the group list is one of the constants, and every
// constant is in the list: a new group constant that nobody added to
// AllGroups would never reach the consumer's switch.
func TestAllGroupsCoversTheConstants(t *testing.T) {
	listed := make(map[string]bool, len(AllGroups()))
	for _, g := range AllGroups() {
		require.False(t, listed[g], "group %q listed twice", g)
		listed[g] = true
	}
	for _, g := range []string{
		GroupFieldTypes, GroupIndexTypes, GroupMetricTypes, GroupFunctions, GroupProviders,
		GroupDeclared, GroupProperties, GroupDBProperties, GroupFieldParams, GroupIndexParams,
		GroupObjects, GroupDist, GroupSegment, GroupLoaded, GroupConfig, GroupRequest,
	} {
		require.True(t, listed[g], "group constant %q is not in AllGroups", g)
	}
}

// Every counter a snapshot produces carries a group from the list, so a
// consumer that switches on AllGroups never meets an unknown one.
func TestSnapshotGroupsAreListed(t *testing.T) {
	listed := make(map[string]bool)
	for _, g := range AllGroups() {
		listed[g] = true
	}
	for _, e := range NewCounters().Snapshot() {
		require.True(t, listed[e.Group], "counter %q has unlisted group %q", e.Name, e.Group)
	}
}
