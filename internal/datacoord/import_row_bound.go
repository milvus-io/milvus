// nonSourceFieldIDs returns field IDs absent from import source files: the
// autoID primary key (generated by Milvus) and all function-output fields
// (generated during import, e.g. a BM25 sparse vector).
func nonSourceFieldIDs(schema *schemapb.CollectionSchema) typeutil.Set[int64] {
	ids := typeutil.NewSet[int64]()
	for _, f := range schema.GetFields() {
		if f.GetIsPrimaryKey() && f.GetAutoID() {
			ids.Insert(f.GetFieldID())
		}
	}
	for _, fn := range schema.GetFunctions() {
		ids.Insert(fn.GetOutputFieldIds()...)
	}
	return ids
}

// minRowTextBytes returns a provable lower bound on the number of bytes one row
// occupies when serialized as JSON/CSV, EXCLUDING fields not present in the source
// files (autoID primary key and function-output fields). Known dense vector fields
// contribute at least one character per element (dim, or dim/8 for binary vectors);
// VarChar/JSON may be empty and contribute 0; unknown/sparse source fields
// contribute 0; every other known fixed scalar contributes at least 1. The result
// is floored to 1 to avoid divide-by-zero downstream.
func minRowTextBytes(schema *schemapb.CollectionSchema) (int64, error) {
	skip := nonSourceFieldIDs(schema)
	var total int64
	for _, field := range schema.GetFields() {
		if skip.Contain(field.GetFieldID()) {
			continue
		}
		// A nullable or defaulted field may be omitted entirely from a JSON row
		// (the reader fills it), contributing 0 bytes. Counting it would overstate
		// the per-row floor and understate the row count, so skip it to keep this a
		// true lower bound.
		if field.GetNullable() || field.GetDefaultValue() != nil {
			continue
		}
		switch field.GetDataType() {
		case schemapb.DataType_Bool, schemapb.DataType_Int8, schemapb.DataType_Int16,
			schemapb.DataType_Int32, schemapb.DataType_Int64,
			schemapb.DataType_Float, schemapb.DataType_Double:
			// Known fixed scalar: at least 1 character.
			total++
		case schemapb.DataType_FloatVector, schemapb.DataType_Float16Vector,
			schemapb.DataType_BFloat16Vector, schemapb.DataType_Int8Vector:
			dim, err := typeutil.GetDim(field)
			if err != nil {
				// Unknown dimension: cannot prove a floor, contributes 0.
				continue
			}
			total += dim
		case schemapb.DataType_BinaryVector:
			dim, err := typeutil.GetDim(field)
			if err != nil {
				continue
			}
			total += dim / 8
		default:
			// VarChar/JSON may be empty; unknown/sparse source fields contribute 0.
		}
	}
	if total < 1 {
		total = 1
	}
	return total, nil
}

// computeFileRowUpperBound returns an upper bound on the row count of one
// ImportFile, and whether that bound is exact. Parquet and numpy record their row
// count in the file itself (footer num_rows / header shape), so both are exact.
// JSON/CSV record nothing, so their bound divides Σ file size by a provable
// per-row byte floor -- a heavy over-estimate that is still guaranteed not to
// under-count. The exactness decides how the caller sizes the reservation and,
// under ID pressure, which reservations it may shrink.
func computeFileRowUpperBound(ctx context.Context, cm storage.ChunkManager,
	schema *schemapb.CollectionSchema, file *internalpb.ImportFile,
) (int64, bool, error) {
	ft, err := importutilv2.GetFileType(file)
	if err != nil {
		return 0, false, err
	}

	sumSize := func() (int64, error) {
		var total int64
		for _, path := range file.GetPaths() {
			size, err := cm.Size(ctx, path)
			if err != nil {
				return 0, err
			}
			total += size
		}
		return total, nil
	}

	var bound int64
	var exact bool
	switch ft {
	case importutilv2.Parquet:
		bound, err = parquetNumRows(ctx, cm, file.GetPaths()[0])
		if err != nil {
			return 0, false, err
		}
		exact = true
	case importutilv2.Numpy:
		bound, err = numpyNumRows(ctx, cm, file.GetPaths())
		if err != nil {
			return 0, false, err
		}
		exact = true
	case importutilv2.JSON, importutilv2.CSV, importutilv2.JSONLines:
		// No row count is recorded in the file, so divide the byte size by a
		// provable per-row floor. This over-estimates heavily (the floor is 1 byte
		// for an all-VarChar schema) and must stay an upper bound: under-estimating
		// would exhaust the range and fail the import at the datanode guard.
		minRow, _ := minRowTextBytes(schema)
		total, err := sumSize()
		if err != nil {
			return 0, false, err
		}
		bound = total/minRow + 1
	default:
		return 0, false, merr.WrapErrImportFailed("unknown import file type for PK range sizing")
	}

	if bound < 0 {
		bound = 0
	}
	return bound, exact, nil
}

// numpyNumRows reads only the .npy headers to get the exact row count of one
// column-based import file. Every path belongs to the same rows, so their shapes
// agree on a well-formed input; the maximum is taken so a disagreement can only
// over-reserve rather than under-reserve (the reader rejects the mismatch later).
// Paths for omitted nullable/default columns are simply absent and contribute
// nothing.
func numpyNumRows(ctx context.Context, cm storage.ChunkManager, paths []string) (int64, error) {
	var rows int64
	for _, path := range paths {
		// The header itself is read through RetryableReader (which retries Read),
		// so only classification matters here: a transient object-store fault must
		// stay a retriable IO error, not a non-retriable ImportFailed input error.
		cmReader, err := cm.Reader(ctx, path)
		if err != nil {
			return 0, storage.ToMilvusIoError(path, err)
		}
		r, err := npyio.NewReader(importutilv2common.NewRetryableReader(ctx, path, cmReader))
		if err != nil {
			cmReader.Close()
			return 0, storage.ToMilvusIoError(path, err)
		}
		shape := r.Header.Descr.Shape
		cmReader.Close()
		if len(shape) == 0 {
			continue
		}
		if n := int64(shape[0]); n > rows {
			rows = n
		}
	}
	return rows, nil
}

// parquetNumRows reads only the parquet footer to get the exact row count. The
// footer is read via Seek/ReadAt, which RetryableReader (Read-only) does not cover,
// so the whole open-and-read is wrapped in retry to survive a transient object-store
// fault; a transient failure is classified as a retriable IO error, not a
// non-retriable ImportFailed input error.
func parquetNumRows(ctx context.Context, cm storage.ChunkManager, path string) (int64, error) {
	var rows int64
	err := retry.Handle(ctx, func() (bool, error) {
		cmReader, err := cm.Reader(ctx, path)
		if err != nil {
			ioErr := storage.ToMilvusIoError(path, err)
			return !merr.IsNonRetryableErr(ioErr), ioErr
		}
		retryableReader := importutilv2common.NewRetryableReader(ctx, path, cmReader)
		defer retryableReader.Close()
		pr, err := file.NewParquetReader(retryableReader)
		if err != nil {
			ioErr := storage.ToMilvusIoError(path, err)
			return !merr.IsNonRetryableErr(ioErr), ioErr
		}
		defer pr.Close()
		rows = pr.NumRows()
		return false, nil
	})
	return rows, err
}

// assignPKRangesToFiles computes a per-file row upper bound, allocates one
// contiguous primary-namespace id block sized Σbound via allocN, then writes each
// file its own contiguous [PkIdBegin, PkIdEnd) slice in the given files order.
// It is called on the PRIMARY at import broadcast for non-backup autoID imports;
// the ranges then travel on the replicated ImportMsg so both clusters derive
// identical primary keys. The layout is bound to each file object, so it survives
// later file regrouping/reordering.
func assignPKRangesToFiles(ctx context.Context, cm storage.ChunkManager,
	schema *schemapb.CollectionSchema, files []*internalpb.ImportFile,
	allocN func(int64) (int64, int64, error), clusterID uint64,
) error {
	bounds, exacts, err := computeFileRowUpperBounds(ctx, cm, schema, files)
	if err != nil {
		return err
	}
	sizeReservations(bounds, exacts)
	return reserveRanges(bounds, files, allocN, clusterID)
}

// maxIDsPerAllocBatch mirrors the per-call ceiling of rootCoordAllocator.AllocN.
const maxIDsPerAllocBatch = int64(math.MaxUint32)

// reserveRanges writes each file its own contiguous [PkIdBegin, PkIdEnd) slice,
// chunking the allocation so that no single allocN call exceeds the allocator's
// per-batch ceiling. Files are packed greedily and a file's range never straddles
// two batches, so every range stays contiguous while the import as a whole is not
// capped at one batch: the reservation total may exceed the ceiling, only a single
// file may not.
func reserveRanges(bounds []int64, files []*internalpb.ImportFile,
	allocN func(int64) (int64, int64, error), clusterID uint64,
) error {
	for i := 0; i < len(bounds); {
		var batch int64
		j := i
		for ; j < len(bounds); j++ {
			if bounds[j] > maxIDsPerAllocBatch {
				return merr.WrapErrParameterInvalidMsg(
					"import file %d needs %d primary keys, more than one allocation batch holds (max %d)",
					j, bounds[j], maxIDsPerAllocBatch)
			}
			if batch+bounds[j] > maxIDsPerAllocBatch {
				break
			}
			batch += bounds[j]
		}
		if batch == 0 {
			// Only reachable once every remaining bound is zero, which
			// sizeReservations rules out; guards against a non-advancing loop.
			return nil
		}
		begin, _, err := common.AllocAutoIDN(allocN, batch, clusterID)
		if err != nil {
			return err
		}
		cur := begin
		for k := i; k < j; k++ {
			files[k].PkIdBegin = cur
			files[k].PkIdEnd = cur + bounds[k]
			cur = files[k].PkIdEnd
		}
		i = j
	}
	return nil
}

// computeFileRowUpperBounds sizes every file concurrently. Sizing is object-store
// IO (a HEAD per path, or a footer/header read) on the import broadcast path, and
// the request may carry up to dataCoord.maxFilesPerImportReq files, so doing it
// serially would turn a millisecond RPC into a minutes-long one.
func computeFileRowUpperBounds(ctx context.Context, cm storage.ChunkManager,
	schema *schemapb.CollectionSchema, files []*internalpb.ImportFile,
) ([]int64, []bool, error) {
	bounds := make([]int64, len(files))
	exacts := make([]bool, len(files))
	pool := conc.NewPool[struct{}](hardware.GetCPUNum() * 2)
	defer pool.Release()

	futures := make([]*conc.Future[struct{}], 0, len(files))
	for i, f := range files {
		i, f := i, f
		futures = append(futures, pool.Submit(func() (struct{}, error) {
			b, exact, err := computeFileRowUpperBound(ctx, cm, schema, f)
			if err != nil {
				return struct{}{}, err
			}
			bounds[i], exacts[i] = b, exact
			return struct{}{}, nil
		}))
	}
	if err := conc.AwaitAll(futures...); err != nil {
		return nil, nil, err
	}
	return bounds, exacts, nil
}

// sizeReservations turns per-file row counts into per-file id reservations.
//
// An exact count gets the configured expansion factor as headroom, matching how
// import already over-reserves logIDs; the headroom absorbs a reader producing
// slightly more rows than the footer/header advertised. A byte-derived estimate is
// already a gross over-estimate, so multiplying it would only waste id space.
//
// Every reservation is at least one id. The datanode reads an empty range as "no
// range" and silently falls back to its local allocator, which is the divergence
// this whole mechanism exists to prevent, so a zero-row file still gets a slice.
//
// Reservations are never shrunk to fit an allocation ceiling: the JSON/CSV bound
// is only usable because it is guaranteed not to under-count, and scaling it down
// would break that guarantee and surface as a mid-import failure on the datanode.
// reserveRanges splits the allocation across batches instead.
func sizeReservations(bounds []int64, exacts []bool) {
	factor := paramtable.Get().DataCoordCfg.ImportPreAllocIDExpansionFactor.GetAsInt64()
	if factor < 1 {
		factor = 1
	}
	for i, b := range bounds {
		if exacts[i] {
			b *= factor
		}
		if b < 1 {
			b = 1
		}
		bounds[i] = b
	}
}
