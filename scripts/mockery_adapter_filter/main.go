// mockery_adapter_filter keeps handwritten mockey adapters authoritative after
// regenerating legacy mocks. It removes only methods supplied by the adapter,
// together with the corresponding Mockery EXPECT helpers.
package main

import (
	"bytes"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		panic("usage: mockery_adapter_filter adapter.go generated-directory")
	}
	if err := filterAdapters(os.Args[1], os.Args[2]); err != nil {
		panic(err)
	}
}

func receiver(fn *ast.FuncDecl) string {
	if fn.Recv == nil {
		return ""
	}
	typ := fn.Recv.List[0].Type
	if ptr, ok := typ.(*ast.StarExpr); ok {
		typ = ptr.X
	}
	// Generic receivers wrap the base type name in an instantiation expression.
	switch instantiated := typ.(type) {
	case *ast.IndexExpr:
		typ = instantiated.X
	case *ast.IndexListExpr:
		typ = instantiated.X
	}
	return typ.(*ast.Ident).Name
}

func filterAdapters(adapter, dir string) error {
	fset := token.NewFileSet()
	source, err := parser.ParseFile(fset, adapter, nil, 0)
	if err != nil {
		return err
	}
	methods, calls := make(map[string]bool), make(map[string]bool)
	for _, decl := range source.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok && fn.Recv != nil {
			typ := receiver(fn)
			methods[typ+"."+fn.Name.Name] = true
			methods[typ+"_Expecter."+fn.Name.Name] = true
			calls[typ+"_"+fn.Name.Name+"_Call"] = true
		}
	}
	paths, err := filepath.Glob(filepath.Join(dir, "mock_*.go"))
	if err != nil {
		return err
	}
	for _, path := range paths {
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		if !ast.IsGenerated(file) {
			continue
		}
		comments := ast.NewCommentMap(fset, file, file.Comments)
		var kept []ast.Decl
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if methods[receiver(d)+"."+d.Name.Name] || calls[receiver(d)] {
					continue
				}
			case *ast.GenDecl:
				// Mockery emits one call-helper type per declaration.
				if d.Tok == token.TYPE && len(d.Specs) == 1 && calls[d.Specs[0].(*ast.TypeSpec).Name.Name] {
					continue
				}
			}
			kept = append(kept, decl)
		}
		if len(kept) == len(file.Decls) {
			continue
		}
		file.Decls = kept
		file.Comments = comments.Filter(file).Comments()
		// Preserve the generated marker even if its original declaration went.
		var output bytes.Buffer
		if err := format.Node(&output, fset, file); err != nil {
			return err
		}
		data := output.Bytes()
		if !strings.Contains(string(data), "Code generated") {
			data = append([]byte("// Code generated by mockery. DO NOT EDIT.\n\n"), data...)
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}
