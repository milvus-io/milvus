package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestFilterAdapters(t *testing.T) {
	dir := t.TempDir()
	adapter := filepath.Join(dir, "adapters.go")
	require.NoError(t, os.WriteFile(adapter, []byte(`package mocks
func (*MockCoord) GetRetention() {}
func helper() {}
`), 0o644))
	generated := filepath.Join(dir, "mock_coord.go")
	input := `// Code generated by mockery v2.53.3. DO NOT EDIT.
package mocks
type MockCoord struct{}
type MockCoord_Expecter struct{}
// GetRetention is replaced by the handwritten adapter.
func (*MockCoord) GetRetention() {}
func (*MockCoord_Expecter) GetRetention() {}
type MockCoord_GetRetention_Call struct{}
func (*MockCoord_GetRetention_Call) Return() {}
func (MockCoord_GetRetention_Call) Run() {}
// Other RPC methods and their helpers remain generated.
func (*MockCoord) Other() {}
func (*MockCoord_Expecter) Other() {}
type MockCoord_Other_Call struct{}
func (*MockCoord_Other_Call) Return() {}
func helper() {}
`
	require.NoError(t, os.WriteFile(generated, []byte(input), 0o644))
	manual := filepath.Join(dir, "mock_manual.go")
	require.NoError(t, os.WriteFile(manual, []byte("package mocks\nfunc (*MockCoord) GetRetention() {}\n"), 0o644))
	require.NoError(t, filterAdapters(adapter, dir))
	result, err := os.ReadFile(generated)
	require.NoError(t, err)
	require.NotContains(t, string(result), "GetRetention")
	require.Contains(t, string(result), "Other()")
	require.Contains(t, string(result), "MockCoord_Other_Call")
	require.Contains(t, string(result), "func helper()")
	require.Contains(t, string(result), "Code generated by mockery")
	untouched, err := os.ReadFile(manual)
	require.NoError(t, err)
	require.Contains(t, string(untouched), "GetRetention")
	require.NoError(t, filterAdapters(adapter, dir))
	again, err := os.ReadFile(generated)
	require.NoError(t, err)
	require.Equal(t, result, again, "regeneration filtering must be idempotent")
	require.Error(t, filterAdapters(filepath.Join(dir, "missing.go"), dir))
	require.NoError(t, os.WriteFile(generated, []byte("invalid Go"), 0o644))
	require.Error(t, filterAdapters(adapter, dir))
}

func TestCommandArguments(t *testing.T) {
	original := os.Args
	t.Cleanup(func() { os.Args = original })
	os.Args = []string{"mockery_adapter_filter"}
	require.Panics(t, main)
	dir := t.TempDir()
	adapter := filepath.Join(dir, "adapter.go")
	os.Args = []string{"mockery_adapter_filter", adapter, dir}
	require.Panics(t, main, "generation must fail if its adapter cannot be read")
	require.NoError(t, os.WriteFile(adapter, []byte("package mocks\n"), 0o644))
	require.NotPanics(t, main)
}
